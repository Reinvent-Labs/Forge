/**
 * @forge/agent-onboarding
 *
 * The Onboarding Agent handles the full lifecycle of bringing a new project
 * or developer onto the Forge platform. For projects, it generates a
 * technical spec, executes an initialization checklist, and sends a summary
 * to the configured notification channel. For developers, it generates a
 * personalized onboarding package. It also generates structured postmortems
 * for resolved incidents.
 */

import Anthropic from '@anthropic-ai/sdk'
import { createLogger } from '@forge/shared'
import { prisma } from '@forge/database'
import { randomUUID } from 'crypto'

const log = createLogger('agent-onboarding')

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

/**
 * Input for onboarding a new project onto the Forge platform.
 */
export interface ProjectOnboardingInput {
  organizationId: string
  productDescription: string
  targetUsers: string
  coreWorkflow: string
  existingRepoUrl?: string
  preferredHosting?: 'vercel' | 'railway' | 'render' | 'fly' | 'auto'
  connectedServices?: string[]
  notificationPreference?: 'slack' | 'telegram'
  notificationWebhook?: string
  autonomyLevel?: 'suggest' | 'semi' | 'autonomous'
  founderName: string
  founderEmail: string
}

/**
 * Technical specification generated by Claude Sonnet during onboarding.
 */
export interface TechSpec {
  recommendedStack: { technology: string; rationale: string }[]
  dataModel: string
  apiSurface: { endpoint: string; method: string; description: string }[]
  thirdPartyIntegrations: string[]
  estimatedSetupTimeHours: number
}

/**
 * Result of a completed project onboarding flow.
 */
export interface OnboardingResult {
  projectId: string
  organizationId: string
  techSpec: TechSpec
  completedSteps: OnboardingStep[]
  failedSteps: OnboardingStep[]
  initialPrUrl?: string
  architectureDocUrl?: string
  summary: string
}

export interface OnboardingStep {
  name: string
  status: 'completed' | 'failed' | 'skipped'
  details?: string
  error?: string
}

/**
 * Onboarding package generated for a new developer joining a project.
 */
export interface DevOnboardingResult {
  projectId: string
  developerName: string
  setupScript: string
  architectureMarkdown: string
  gettingStartedMarkdown: string
  openIssuesSummary: string
  suggestedFirstPR: string
  adrLinks: string[]
  generatedAt: Date
}

/**
 * Structured postmortem document for a resolved incident.
 */
export interface PostmortemDocument {
  incidentId: string
  projectId: string
  title: string
  severity: string
  timeline: TimelineEvent[]
  rootCauseAnalysis: string
  impactAssessment: {
    usersAffected: number | null
    durationMinutes: number
    revenueImpact: string
  }
  whatWentWell: string[]
  whatWentWrong: string[]
  actionItems: ActionItem[]
  plainEnglishSummary: string
  generatedAt: Date
}

export interface TimelineEvent {
  timestamp: Date
  description: string
  actor: string
}

export interface ActionItem {
  description: string
  owner: string
  dueDate: Date
  priority: 'critical' | 'high' | 'medium' | 'low'
}

