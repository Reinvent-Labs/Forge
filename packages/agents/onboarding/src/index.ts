  private async stepOpenInitialPR(
    projectId: string,
    input: ProjectOnboardingInput,
  ): Promise<OnboardingStep> {
    try {
      log.info({ projectId }, 'Opening initial PR: Infrastructure baseline')
      await prisma.agentTask.create({
        data: {
          id: randomUUID(),
          projectId,
          type: 'BUILD_FEATURE',
          priority: 'NORMAL',
          agentType: 'BUILDER',
          requestedBy: 'SYSTEM',
          autonomyLevel: (input.autonomyLevel?.toUpperCase() ?? 'SUGGEST') as never,
          payload: { step: 'initial_pr', title: 'Infrastructure baseline' },
        },
      })
      return { name: 'Open initial PR: Infrastructure baseline', status: 'completed', details: 'Initial PR task queued for Builder agent' }
    } catch (err) {
      return { name: 'Open initial PR: Infrastructure baseline', status: 'failed', error: err instanceof Error ? err.message : String(err) }
    }
  }

