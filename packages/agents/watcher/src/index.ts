/**
 * @forge/agent-watcher
 *
 * Production log monitoring and anomaly detection agent.
 *
 * Responsibilities:
 * 1. Fetch logs from Vercel, Railway, and Fly.io APIs.
 * 2. Normalize provider-specific payloads into a stable LogEvent shape.
 * 3. Detect statistical anomalies (error-rate spikes, p95/p99 latency increases).
 * 4. Classify and persist alerts.
 * 5. Trigger Fixer tasks for critical alerts.
 * 6. Publish real-time alert events to the orchestrator EventBus.
 */

import Anthropic from '@anthropic-ai/sdk'
import { randomUUID } from 'crypto'
import { prisma } from '@forge/database'
import { createLogger, normalizeErrorFingerprint } from '@forge/shared'
import type {
  AgentTask,
  ForgeEvent,
  LogEvent,
} from '@forge/shared'
import type { Redis } from 'ioredis'

const log = createLogger('agent-watcher')

const ANTHROPIC_MODEL = 'claude-haiku-4-5-20251001'

const ALERT_SEVERITIES = ['info', 'warning', 'error', 'critical'] as const

type WatcherAlertSeverity = (typeof ALERT_SEVERITIES)[number]
type LogProvider = 'vercel' | 'railway' | 'fly'
type MetricName = 'error_rate' | 'latency_p95' | 'latency_p99'
type AlertType = 'anomaly' | 'error_pattern' | 'classified_alert'

/**
 * Normalized log entry consumed by anomaly detection and alerting.
 */
export interface NormalizedLogEntry extends LogEvent {
  provider: LogProvider
  latencyMs?: number
  statusCode?: number
}

/**
 * Structured alert generated by WatcherAgent.
 */
export interface WatcherAlert {
  id: string
  projectId: string
  organizationId: string
  type: AlertType
  severity: WatcherAlertSeverity
  title: string
  description: string
  detectedAt: Date
  fingerprint: string
  metricName?: MetricName
  currentValue?: number
  baselineMean?: number
  baselineStdDev?: number
  sigma?: number
  eventIds: string[]
  metadata: Record<string, unknown>
}

/**
 * Top-level task result envelope for orchestrator responses.
 */
export interface WatcherResult {
  taskId: string
  projectId: string
  success: boolean
  sourcesChecked: LogProvider[]
  logsFetched: number
  normalizedLogs: number
  anomaliesDetected: number
  alertsCreated: number
  criticalAlerts: number
  fixerTasksTriggered: number
  retentionWindowMinutes: number
  alerts: WatcherAlert[]
  error?: string
  completedAt: Date
}

