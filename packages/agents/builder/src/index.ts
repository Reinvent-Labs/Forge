/**
 * Parse <file ...> blocks from Claude's structured response.
 *
 * Each block carries the full file content and metadata (path, action).
 * Blocks that cannot be parsed are silently skipped.
 *
 * @param response - The raw text response from Claude
 */
function parseFileChanges(response: string): FileChange[] {
  const changes: FileChange[] = []
  // Match <file path="..." action="create|modify|delete"> ... </file> blocks
  const fileBlockRegex =
    /<file\s+path="([^"]+)"\s+action="(create|modify|delete)"[^>]*>([\s\S]*?)<\/file>/g
  let match: RegExpExecArray | null
  while ((match = fileBlockRegex.exec(response))  !== null) {
    const [, filePath, action, content] = match
    if (filePath && action) {
      changes.push({
        filePath,
        action: action as FileChange['action'],
        // Strip leading/trailing blank lines that Claude sometimes inserts
        content: (content ?? '').trim(),
      })
    }
  }
  return changes
}

/**
 * Extract the content of a labelled section from Claude's response.
 *
 * Sections are expected in the form "SECTION_NAME: content" and end at
 * the next labelled section (WORD: pattern) or end-of-string.
 *
 * @param response - The full text response from Claude
 * @param sectionName - The uppercase section label to look for
 */
function extractSection(response: string, sectionName: string): string | undefined {
  // Match SECTION_NAME: <content> up to the next ALL_CAPS: label or end-of-string
  const regex = new RegExp(sectionName + String.fromCharCode(58) + '\\s*([\\s\\S]*?)(?=\\n[A-Z_]+:|$)', '')
  const match = regex.exec(response)
  return match?.[1]?.trim()
}

// ---------------------------------------------------------------------------
// File-system helpers
// ---------------------------------------------------------------------------

/**
 * Write parsed file changes into the given working directory.
 *
 * Creates parent directories as needed.
 * Files whose action is 'delete' are removed; non-existent deletes are no-ops.
 *
 * @param workDir - Absolute path to the working directory
 * @param changes - Parsed file changes to apply
 */
function applyFileChanges(workDir: string, changes: FileChange[]): void {
  for (const change of changes) {
    const fullPath = path.join(workDir, change.filePath)
    const dir = path.dirname(fullPath)
    if (change.action === 'delete') {
      try { fs.unlinkSync(fullPath) } catch { /* file may not exist */ }
      continue
    }
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(fullPath, change.content, 'utf-8')
  }
}

