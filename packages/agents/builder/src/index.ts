interface PrBodyOptions {
  businessImpact: string
  technicalRationale: string
  fileChanges: FileChange[]
  checks: CheckResult
  confidenceScore?: ConfidenceScore
  taskId: string
}

/**
 * Interpolate the PR_TEMPLATE with values derived from the build result.
 *
 * Produces a dual-register description: plain English for founders in
 * "What changed"; technical details for engineers in subsequent sections.
 *
 * @param opts - Values to interpolate into the template
 */
function buildPrBody(opts: PrBodyOptions): string {
  const { businessImpact, technicalRationale, fileChanges, checks, confidenceScore } = opts

  const filesSummary = fileChanges
    .map((f) => `- \`${f.filePath}\` (${f.action})`)
    .join('\n')

  const coveragePercent = checks.coverage  !== undefined ? checks.coverage.toFixed(1) : 'N/A'
  const newTestCount = fileChanges.filter(
    (f) => f.filePath.includes('.test.') || f.filePath.includes('.spec.'),
  ).length
  const ciStatus = checks.passed ? 'Yes' : `No — ${checks.errors.slice(0, 2).join('; ')}` 
  const score = confidenceScore?.total ?? 'N/A'
  const confidenceBreakdown = confidenceScore
    ? Object.entries(confidenceScore.breakdown)
        .map(([k, v]) => `- ${k}: ${v}`)
        .join('\n')
    : 'Confidence score unavailable (CI did not run).'
  const riskFactors =
    confidenceScore && confidenceScore.riskFactors.length > 0
      ? confidenceScore.riskFactors.map((r) => `- ${r}`)
          .join('\n')
      : '- None identified'
  const rollbackInstructions =
    "Revert this PR via GitHub's 'Revert' button, or run:\n" +
    '```\ngit revert HEAD --no-edit && git push\n```'

  return PR_TEMPLATE
    .replace('{businessImpact}', businessImpact)
    .replace('{technicalRationale}', technicalRationale)
    .replace('{filesSummary}', filesSummary)
    .replace('{coveragePercent}', String(coveragePercent))
    .replace('{newTestCount}', String(newTestCount))
    .replace('{ciStatus}', ciStatus)
    .replace('{score}', String(score))
    .replace('{confidenceBreakdown}', confidenceBreakdown)
    .replace('{riskFactors}', riskFactors)
    .replace('{rollbackInstructions}', rollbackInstructions)
    .replace('{timestamp}', new Date().toISOString())
}

