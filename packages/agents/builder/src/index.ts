/**
 * @forge/agent-builder — Builder Agent
 *
 * Responsible for code generation, feature implementation, test generation,
 * PR review, and refactoring. Uses Claude claude-sonnet-4-6 for all AI-driven
 * tasks and Octokit for GitHub PR management.
 *
 * Flow for feature builds:
 *   1. Receive AgentTask with XML-formatted codebase context (injected by ContextManager)
 *   2. Call Claude with context + task description to generate file changes
 *   3. Apply changes to a temp working directory
 *   4. Run lint / typecheck / test checks
 *   5. Compute a confidence score
 *   6. Open a GitHub PR with dual-register description (technical + plain English)
 */

import Anthropic from '@anthropic-ai/sdk'
import { Octokit } from 'octokit'
import { execSync } from 'child_process'
import * as fs from 'fs'
import * as path from 'path'
import * as os from 'os'
import { createLogger } from '@forge/shared'
import type { AgentTask, ConfidenceScore } from '@forge/shared'
import { prisma } from '@forge/database'
import { ConfidenceEngine } from '@forge/orchestrator'
import type { ConfidenceInputs } from '@forge/orchestrator'

const log = createLogger('agent-builder')

// ---------------------------------------------------------------------------
// Types and Interfaces
// ---------------------------------------------------------------------------

/** Result returned by every BuilderAgent public method. */
export interface BuilderResult {
  success: boolean
  prUrl?: string
  prNumber?: number
  filesChanged: string[]
  summary: string
  confidenceScore?: ConfidenceScore
}

/** Result from running quality checks in a temp working directory. */
export interface CheckResult {
  passed: boolean
  lintPassed: boolean
  typecheckPassed: boolean
  testsPassed: boolean
  /** Code coverage percentage, if available from the test runner output. */
  coverage?: number
  errors: string[]
}

/** Options for opening a GitHub pull request. */
interface PrOptions {
  owner: string
  repo: string
  branch: string
  baseBranch: string
  title: string
  body: string
}

/** A single file change parsed from Claude's response. */
interface FileChange {
  filePath: string
  content: string
  action: 'create' | 'modify' | 'delete'
}

/** Parsed payload for build_feature tasks. */
interface BuildFeaturePayload {
  description: string
  contextPrompt?: string
  repoOwner?: string
  repoName?: string
  baseBranch?: string
}

/** Parsed payload for generate_tests tasks. */
interface GenerateTestsPayload {
  filesChanged: string[]
  contextPrompt?: string
  repoOwner?: string
  repoName?: string
  baseBranch?: string
}

/** Parsed payload for review_pr tasks. */
interface ReviewPrPayload {
  prNumber: number
  repoOwner: string
  repoName: string
}

/** Parsed payload for refactor tasks. */
interface RefactorPayload {
  instructions: string
  targetFiles?: string[]
  contextPrompt?: string
  repoOwner?: string
  repoName?: string
  baseBranch?: string
}

