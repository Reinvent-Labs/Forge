function buildSummary(
  fileChanges: FileChange[],
  checks: CheckResult,
  prUrl: string | undefined,
): string {
  const fileList = fileChanges.map((f) => f.filePath).join(', ')
  const checkStatus = checks.passed ? 'all checks passed' : 'some checks failed'
  const pr = prUrl ? ` PR: ${prUrl}` : ''
  return `Changed ${fileChanges.length} file(s) (${fileList}); ${checkStatus}.${pr}`
}

function extractPrNumber(prUrl: string): number | undefined {
  const match = /\/pull\/(\d+)$/.exec(prUrl)
  return match?.[1] ? parseInt(match[1], 10) : undefined
}

/**
 * Persist the task outcome to the AgentTask DB record.
 *
 * Errors are swallowed intentionally — a DB write failure must never block
 * the task result from being returned to the orchestrator.
 *
 * @param task - The originating agent task
 * @param success - Whether the task overall succeeded
 * @param filesChanged - Relative paths of modified files
 */
async function recordTaskResult(
  task: AgentTask,
  success: boolean,
  filesChanged: string[],
): Promise<void> {
  try {
    await prisma.agentTask.update({
      where: { id: task.id },
      data: {
        status: success ? 'COMPLETED' : 'FAILED',
        result: { success, filesChanged } as object,
        completedAt: new Date(),
      },
    })
  } catch (err) {
    log.warn({ taskId: task.id, err }, 'Could not update AgentTask record in DB')
  }
}
